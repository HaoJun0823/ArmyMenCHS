// linefix.h —— 长文本分行"多写一行"的修复
//
// ════════════════════════════════════════════════════════════════════════
//  根因（IDA 反汇编 + x32dbg 运行时数据双向确认）
// ════════════════════════════════════════════════════════════════════════
//
//  无线电面板的文本在 sub_42EF50 里被切成多行，存进
//  「每行 129 字节 × 最多 16 行」的行数组（this+0x8D9 起），
//  行数存在 this+0x8EC。
//
//  行末处理（amat.exe 0x42F067 起，IDA 实测）：
//        0x42F067  cmp  byte [ebx], 0      ; ebx = 源串当前字节
//        0x42F06A  jz   loc_42F074         ; ★ 源串已结束 -> 仍去"写一行"
//        0x42F06C  test al, al              ; al = 本轮是否发生断行
//        0x42F06E  jz   loc_42F130         ; 没断行 -> 回到循环顶部
//        0x42F074  mov  edx, [ebp+8ECh]    ; ---- 以下是"写一行" ----
//        0x42F07F  inc  edx
//        0x42F082  mov  [ebp+8ECh], edx    ; ★ 行数 +1
//        ...
//        0x42F0FE  strcpy(行数组[n], buf)   ; 把当前缓冲写进第 n 行
//
//  ★★ 问题：0x42F06A 的 jz 让"源串已结束"也落到写行路径，
//     于是每次分行结束都会**多写一行**，并把行数 +1。
//     那一行的缓冲是从未初始化的堆内存 —— x32dbg 实读到的是
//     重复的 0DF0ADBA（VC++ debug 堆的已释放块标记）。
//
//  ★★ 后果：sub_42EB90 按行数绘制，逐行调用 sub_4887F0，
//     于是把 0DF0ADBA... 当成单字节文字画出来 ——
//     这就是"第二行起整行乱码"。因为这些字节与原文毫无关系，
//     穷举原文所有字节偏移都无法复现截图里的乱码（已验证）。
//
// ════════════════════════════════════════════════════════════════════════
//  修法
// ════════════════════════════════════════════════════════════════════════
//
//  把「源串已结束」与「真正断行」两种情况分开：
//      源串已结束 -> 跳到 while 循环顶部的收尾判定（0x42F130），
//                    那里会立刻再判一次 *ebx==0 并正常收尾。
//      真正断行   -> 保持原样，走 0x42F074 写行。
//
//  ★ 为什么不能用 2 字节 rel8 直接改：
//      0x42F130 - (0x42F06A + 2) = +196，超出 rel8 的 [-128,+127]。
//      0x42F13D（函数收尾）= +209，更远。
//      → 必须用 trampoline（jmp 到我们分配的壳，由壳决定去向）。
//
//  ★ 替换范围：0x42F06A 起 **8 字节**
//        74 08        jz  short +0x08      (2)
//        84 C0        test al, al           (2)
//        0F 84 BC 00  jz  near  +0xBC      (4)
//    8 字节正好是 3 条完整指令，落在指令边界内。
//    替换为 E9 rel32（5 字节）+ 3 字节 NOP。
//
//  ★★ 版本演进（三次失败，根因各不相同）
//
//   v1：只改 `jz` 的目标为 0x42F130，未断行路径也一起改 ->
//       空对话（edi==0 时提前退出）。
//   v2：把"源串结束"和"未断行"都跳去 0x42F10E（初始化段）->
//       每个字符都触发写行，行数暴涨，最终越界崩溃（17:31:44）。
//   v3：**只改"源串结束"这一条**；未断行、真断行完全保持原样 ->
//       这才是最小修正。
//
//  ★ 0x42F130 是 while 条件（cmp byte [ebx],0），不是循环体入口。
//    0x42F10E..0x42F12A 是"写完一行后的初始化"（xor edi / lea esi /
//    插 '^'+颜色 / 行高累加），两者不能混用。
//
//  壳的逻辑（三条路径，命中即走）：
//        if (*ebx == 0)  -> jmp 0x42F130   ; 源串结束：不写行，回 while
//        if (al == 0)    -> jmp 0x42F130   ; 未断行：与原版一致
//        else            -> jmp 0x42F074   ; 真断行：与原版一致，写行
//
//  ★ 源串结束时：0x42F130 判 *ebx==0 -> 走 0x42F139 正常收尾。
//    因此不再写脏行、行数不再 +1，乱码消失。
//
//  ★ 替换范围：0x42F06A 起 **8 字节**
//        74 08        jz  short +0x08      (2)
//        84 C0        test al, al           (2)
//        0F 84 BC 00  jz  near  +0xBC      (4)
//    8 字节 = 3 条完整指令，落在指令边界内。
//    替换为 E9 rel32（5 字节）+ 3 字节 NOP。
#pragma once

#include <windows.h>
#include <string>

struct LineFixConfig {
    DWORD  siteVA  = 0;      // 0x42F06A：待替换的指令起点
    DWORD  patchLen = 0;     // 8
    DWORD  loopTopVA = 0;     // 0x42F130：while 循环条件（不是 0x42F10E）
    DWORD  writeRowVA = 0;    // 0x42F074：写行代码起点
    BYTE   sig[16] = {0};     // 期望的原始 8 字节
    int    sigLen = 0;
    std::string logTag;
};

bool LineFixInstall(const struct LineFixConfig& cfg);
void LineFixRemove();
bool LineFixIsActive();